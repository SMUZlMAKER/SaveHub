// Сценарий ролика: порядок сцен, подписи и какой кусок футажа брать.
// Футаж лежит в public/footage/ и не хранится в git.
//
// Пока файла нет, оставьте ready: false — вместо видео будет заглушка
// с описанием кадра. Когда футаж снят: положите файл, поставьте ready: true
// и подберите from/duration (секунды от начала файла).

export type Shot = {
  kind: "clip";
  id: string;
  file: string;
  ready: boolean;
  /** С какой секунды файла начинать. */
  from: number;
  /** Сколько секунд показывать. */
  duration: number;
  /** Подпись внизу кадра. */
  caption: string;
  /** Что снимать — видно на заглушке, пока футажа нет. */
  todo: string;
  /** Ускорение, если действие в кадре слишком долгое. */
  playbackRate?: number;
  /**
   * Увеличение: scale — во сколько раз, x/y — точка, к которой приближаем
   * (доли ширины и высоты записи, 0…1). Нужно, когда интерфейс мелкий.
   */
  zoom?: { scale: number; x: number; y: number };
  /** Плашка с нажатой комбинацией: at — секунда от начала кадра. */
  keys?: { at: number; label: string[] };
};

export type Scene =
  | Shot
  | { kind: "problem"; duration: number }
  | { kind: "title"; duration: number }
  | { kind: "diagram"; duration: number }
  | { kind: "outro"; duration: number };

